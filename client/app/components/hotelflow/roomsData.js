// Map a backend room document onto the same shape the UI expects.
export function normalizeRoom(apiRoom) {
  const firstImage =
    apiRoom.image || "/images/bd/hotels/hotel-sylhet.jpg";
  return {
    id: String(apiRoom._id || apiRoom.id),
    name: apiRoom.name || "Hotel room",
    hotel: apiRoom.hotel || "",
    address: apiRoom.address || "",
    type: apiRoom.type || "Standard",
    price: Number(apiRoom.price) || 0,
    capacity: Number(apiRoom.capacity) || 2,
    beds: apiRoom.beds || "1 Queen bed",
    bedType: apiRoom.bedType || "Queen",
    size: Number(apiRoom.size) || 300,
    view: apiRoom.view || "City view",
    rating: Number(apiRoom.rating) || 8.0,
    reviews: Number(apiRoom.reviews) || 0,
    available: apiRoom.availableForDates ?? (apiRoom.available !== false && apiRoom.status !== "booked"),
    remainingRooms: apiRoom.remainingRooms ?? apiRoom.totalRooms ?? 1,
    totalRooms:
      apiRoom.totalRooms ||
      { Standard: 8, Single: 10, Double: 8, Deluxe: 6, Suite: 3, Family: 5 }[apiRoom.type] ||
      4,
    amenities: {
      wifi: true,
      ac: true,
      tv: true,
      minibar: ["Deluxe", "Suite"].includes(apiRoom.type),
      balcony: ["Deluxe", "Suite", "Family"].includes(apiRoom.type),
      breakfast: true,
      seaview: false,
      generator: true,
      halal: true,
      prayer: false,
      airport: false,
      ...(apiRoom.amenities || {}),
    },
    images: apiRoom.images?.length ? apiRoom.images : [firstImage],
    description:
      apiRoom.description || "A comfortable room with modern amenities.",
    policies: apiRoom.policies || {
      checkIn: "2:00 PM",
      checkOut: "12:00 PM",
      cancellation: "Free cancellation up to 24 hours before check-in.",
    },
    _raw: apiRoom,
  };
}
